begin;

-- ---------------------------------------------------------
-- 1. ENUMS
-- ---------------------------------------------------------

do $$
begin
  if not exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where t.typname = 'transaction_type'
      and n.nspname = 'public'
  ) then
    create type public.transaction_type as enum (
      'deposit',
      'withdrawal',
      'reversal'
    );
  end if;
end
$$;

do $$
begin
  if not exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where t.typname = 'transaction_status'
      and n.nspname = 'public'
  ) then
    create type public.transaction_status as enum (
      'pending',
      'approved',
      'rejected',
      'reversed'
    );
  end if;
end
$$;

do $$
begin
  if not exists (
    select 1
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where t.typname = 'ledger_direction'
      and n.nspname = 'public'
  ) then
    create type public.ledger_direction as enum (
      'credit',
      'debit'
    );
  end if;
end
$$;

-- ---------------------------------------------------------
-- 2. TRANSACTION REFERENCE SEQUENCE
-- ---------------------------------------------------------

create sequence if not exists public.transaction_reference_seq
  start with 1
  increment by 1;

revoke all on sequence public.transaction_reference_seq from anon, authenticated;

-- ---------------------------------------------------------
-- 3. TRANSACTIONS + IMMUTABLE LEDGER
-- ---------------------------------------------------------

create table if not exists public.transactions (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique,
  customer_id uuid not null references public.customers(id) on delete restrict,
  account_id uuid not null references public.accounts(id) on delete restrict,
  type public.transaction_type not null,
  amount_minor bigint not null,
  status public.transaction_status not null default 'pending',
  description text,
  rejection_reason text,

  initiated_by uuid not null references public.profiles(id) on delete restrict,
  initiated_by_name text not null,
  initiated_at timestamptz not null default now(),

  reviewed_by uuid references public.profiles(id) on delete restrict,
  reviewed_by_name text,
  reviewed_at timestamptz,

  reversal_of uuid references public.transactions(id) on delete restrict,
  reversed_by_transaction_id uuid references public.transactions(id) on delete restrict,

  created_at timestamptz not null default now(),

  constraint transactions_amount_positive check (amount_minor > 0),
  constraint transactions_reversal_shape check (
    (type = 'reversal'::public.transaction_type and reversal_of is not null)
    or
    (type <> 'reversal'::public.transaction_type and reversal_of is null)
  )
);

create table if not exists public.ledger_entries (
  id bigint generated by default as identity primary key,
  transaction_id uuid not null unique references public.transactions(id) on delete restrict,
  account_id uuid not null references public.accounts(id) on delete restrict,
  direction public.ledger_direction not null,
  amount_minor bigint not null,
  balance_before_minor bigint not null,
  balance_after_minor bigint not null,
  posted_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),

  constraint ledger_amount_positive check (amount_minor > 0)
);

create index if not exists transactions_created_at_idx
  on public.transactions (created_at desc);

create index if not exists transactions_status_created_at_idx
  on public.transactions (status, created_at desc);

create index if not exists transactions_account_id_created_at_idx
  on public.transactions (account_id, created_at desc);

create index if not exists transactions_customer_id_created_at_idx
  on public.transactions (customer_id, created_at desc);

create index if not exists transactions_initiated_by_idx
  on public.transactions (initiated_by);

create index if not exists transactions_reversal_of_idx
  on public.transactions (reversal_of);

create index if not exists ledger_entries_account_id_created_at_idx
  on public.ledger_entries (account_id, created_at desc);

