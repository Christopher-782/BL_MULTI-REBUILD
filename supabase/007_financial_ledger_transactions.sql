create or replace function private.current_actor_name()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(nullif(btrim(p.full_name), ''), 'Staff')
  from public.profiles p
  where p.id = (select auth.uid())
  limit 1;
$$;

